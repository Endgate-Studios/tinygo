package p384

// addP sets r = a + b mod p for a and b below p, in constant time. The code is
// unrolled and the carries have no branches, because TinyGo builds with -opt=z.
func addP(r, a, b *nat) {
	a0, a1, a2, a3, a4, a5, a6, a7, a8, a9, a10, a11 := a[0], a[1], a[2], a[3], a[4], a[5], a[6], a[7], a[8], a[9], a[10], a[11]
	b0, b1, b2, b3, b4, b5, b6, b7, b8, b9, b10, b11 := b[0], b[1], b[2], b[3], b[4], b[5], b[6], b[7], b[8], b[9], b[10], b[11]
	s0 := a0 + b0
	c := (a0&b0 | (a0|b0)&^s0) >> 31
	s1 := a1 + b1 + c
	c = (a1&b1 | (a1|b1)&^s1) >> 31
	s2 := a2 + b2 + c
	c = (a2&b2 | (a2|b2)&^s2) >> 31
	s3 := a3 + b3 + c
	c = (a3&b3 | (a3|b3)&^s3) >> 31
	s4 := a4 + b4 + c
	c = (a4&b4 | (a4|b4)&^s4) >> 31
	s5 := a5 + b5 + c
	c = (a5&b5 | (a5|b5)&^s5) >> 31
	s6 := a6 + b6 + c
	c = (a6&b6 | (a6|b6)&^s6) >> 31
	s7 := a7 + b7 + c
	c = (a7&b7 | (a7|b7)&^s7) >> 31
	s8 := a8 + b8 + c
	c = (a8&b8 | (a8|b8)&^s8) >> 31
	s9 := a9 + b9 + c
	c = (a9&b9 | (a9|b9)&^s9) >> 31
	s10 := a10 + b10 + c
	c = (a10&b10 | (a10|b10)&^s10) >> 31
	s11 := a11 + b11 + c
	c = (a11&b11 | (a11|b11)&^s11) >> 31
	// d = s - p, kept when s >= p, which the carry or no borrow tells.
	d0 := s0 - 0xffffffff
	bo := (^s0&0xffffffff | ^(s0^0xffffffff)&d0) >> 31
	d1 := s1 - 0x00000000 - bo
	bo = (^s1&0x00000000 | ^(s1^0x00000000)&d1) >> 31
	d2 := s2 - 0x00000000 - bo
	bo = (^s2&0x00000000 | ^(s2^0x00000000)&d2) >> 31
	d3 := s3 - 0xffffffff - bo
	bo = (^s3&0xffffffff | ^(s3^0xffffffff)&d3) >> 31
	d4 := s4 - 0xfffffffe - bo
	bo = (^s4&0xfffffffe | ^(s4^0xfffffffe)&d4) >> 31
	d5 := s5 - 0xffffffff - bo
	bo = (^s5&0xffffffff | ^(s5^0xffffffff)&d5) >> 31
	d6 := s6 - 0xffffffff - bo
	bo = (^s6&0xffffffff | ^(s6^0xffffffff)&d6) >> 31
	d7 := s7 - 0xffffffff - bo
	bo = (^s7&0xffffffff | ^(s7^0xffffffff)&d7) >> 31
	d8 := s8 - 0xffffffff - bo
	bo = (^s8&0xffffffff | ^(s8^0xffffffff)&d8) >> 31
	d9 := s9 - 0xffffffff - bo
	bo = (^s9&0xffffffff | ^(s9^0xffffffff)&d9) >> 31
	d10 := s10 - 0xffffffff - bo
	bo = (^s10&0xffffffff | ^(s10^0xffffffff)&d10) >> 31
	d11 := s11 - 0xffffffff - bo
	bo = (^s11&0xffffffff | ^(s11^0xffffffff)&d11) >> 31
	mask := -(c | (bo ^ 1))
	r[0] = d0&mask | s0&^mask
	r[1] = d1&mask | s1&^mask
	r[2] = d2&mask | s2&^mask
	r[3] = d3&mask | s3&^mask
	r[4] = d4&mask | s4&^mask
	r[5] = d5&mask | s5&^mask
	r[6] = d6&mask | s6&^mask
	r[7] = d7&mask | s7&^mask
	r[8] = d8&mask | s8&^mask
	r[9] = d9&mask | s9&^mask
	r[10] = d10&mask | s10&^mask
	r[11] = d11&mask | s11&^mask
}

// subP sets r = a - b mod p for a and b below p, in constant time, unrolled as
// addP.
func subP(r, a, b *nat) {
	a0, a1, a2, a3, a4, a5, a6, a7, a8, a9, a10, a11 := a[0], a[1], a[2], a[3], a[4], a[5], a[6], a[7], a[8], a[9], a[10], a[11]
	b0, b1, b2, b3, b4, b5, b6, b7, b8, b9, b10, b11 := b[0], b[1], b[2], b[3], b[4], b[5], b[6], b[7], b[8], b[9], b[10], b[11]
	d0 := a0 - b0
	bo := (^a0&b0 | ^(a0^b0)&d0) >> 31
	d1 := a1 - b1 - bo
	bo = (^a1&b1 | ^(a1^b1)&d1) >> 31
	d2 := a2 - b2 - bo
	bo = (^a2&b2 | ^(a2^b2)&d2) >> 31
	d3 := a3 - b3 - bo
	bo = (^a3&b3 | ^(a3^b3)&d3) >> 31
	d4 := a4 - b4 - bo
	bo = (^a4&b4 | ^(a4^b4)&d4) >> 31
	d5 := a5 - b5 - bo
	bo = (^a5&b5 | ^(a5^b5)&d5) >> 31
	d6 := a6 - b6 - bo
	bo = (^a6&b6 | ^(a6^b6)&d6) >> 31
	d7 := a7 - b7 - bo
	bo = (^a7&b7 | ^(a7^b7)&d7) >> 31
	d8 := a8 - b8 - bo
	bo = (^a8&b8 | ^(a8^b8)&d8) >> 31
	d9 := a9 - b9 - bo
	bo = (^a9&b9 | ^(a9^b9)&d9) >> 31
	d10 := a10 - b10 - bo
	bo = (^a10&b10 | ^(a10^b10)&d10) >> 31
	d11 := a11 - b11 - bo
	bo = (^a11&b11 | ^(a11^b11)&d11) >> 31
	mask := -bo
	m0 := 0xffffffff & mask
	r0 := d0 + m0
	c := (d0&m0 | (d0|m0)&^r0) >> 31
	r1 := d1 + c
	c = d1 &^ r1 >> 31
	r2 := d2 + c
	c = d2 &^ r2 >> 31
	m3 := 0xffffffff & mask
	r3 := d3 + m3 + c
	c = (d3&m3 | (d3|m3)&^r3) >> 31
	m4 := 0xfffffffe & mask
	r4 := d4 + m4 + c
	c = (d4&m4 | (d4|m4)&^r4) >> 31
	m5 := 0xffffffff & mask
	r5 := d5 + m5 + c
	c = (d5&m5 | (d5|m5)&^r5) >> 31
	m6 := 0xffffffff & mask
	r6 := d6 + m6 + c
	c = (d6&m6 | (d6|m6)&^r6) >> 31
	m7 := 0xffffffff & mask
	r7 := d7 + m7 + c
	c = (d7&m7 | (d7|m7)&^r7) >> 31
	m8 := 0xffffffff & mask
	r8 := d8 + m8 + c
	c = (d8&m8 | (d8|m8)&^r8) >> 31
	m9 := 0xffffffff & mask
	r9 := d9 + m9 + c
	c = (d9&m9 | (d9|m9)&^r9) >> 31
	m10 := 0xffffffff & mask
	r10 := d10 + m10 + c
	c = (d10&m10 | (d10|m10)&^r10) >> 31
	m11 := 0xffffffff & mask
	r11 := d11 + m11 + c
	c = (d11&m11 | (d11|m11)&^r11) >> 31
	_ = c
	r[0] = r0
	r[1] = r1
	r[2] = r2
	r[3] = r3
	r[4] = r4
	r[5] = r5
	r[6] = r6
	r[7] = r7
	r[8] = r8
	r[9] = r9
	r[10] = r10
	r[11] = r11
}
